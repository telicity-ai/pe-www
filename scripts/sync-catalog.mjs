// Builds api/_lib/catalog.js from a picky-eater checkout.
//   node scripts/sync-catalog.mjs ../picky-eater
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(process.argv[2] ?? '../picky-eater');
const dir = join(root, 'catalog', 'patterns');
const clip = (text, max) => (text.length > max ? `${text.slice(0, max - 1).trimEnd()}…` : text);

const patterns = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const { category, patterns: list } = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  // Motion cannot be drawn as a still wireframe, so the web preview leaves it out.
  if (category === 'motion') continue;
  for (const p of list) patterns.push({ id: p.id, category, name: p.name, what: clip(p.what, 130) });
}
const ids = new Set(patterns.map((p) => p.id));

const decisions = JSON.parse(readFileSync(join(root, 'catalog', 'decisions.json'), 'utf8'))
  .map((d) => ({
    id: d.id,
    question: d.question,
    candidates: d.candidates.filter((c) => ids.has(c.pattern)).map((c) => ({ pattern: c.pattern, pick: clip(c.pick, 110) })),
  }))
  .filter((d) => d.candidates.length >= 2);

const out = `// Generated by scripts/sync-catalog.mjs from picky-eater's catalog. Do not edit by hand.
export const PATTERNS = ${JSON.stringify(patterns, null, 1)};
export const DECISIONS = ${JSON.stringify(decisions, null, 1)};
`;
writeFileSync(new URL('../api/_lib/catalog.js', import.meta.url), out);
console.log(`${patterns.length} patterns, ${decisions.length} decisions`);
